export function demoAiAnswer(mode: Mode, input: string, ctx: DemoAiContext = {}): string {
  const q = input.trim();
  const topic = q.slice(0, 120);
  const normalized = q.replace(/[\u064B-\u065F\u0640]/g, '').replace(/[أإآ]/g, 'ا');
  const hit = TOPICS.find(t => t.keywords.test(normalized));
  if (mode === 'EXPLAIN_MATCH') {
    return `تحليل المطابقة (نموذج توضيحي) لمنتج «${topic}»:\n• الملاءمة التشغيلية عالية: المعدات المتاحة (فرن دوار وعجانة 50 لتر) تغطي خطوات التحضير الأساسية.\n• هامش الربح المتوقع جيد عند سعر البيع المقترح.\n• يُنصح بدفعة تجريبية صغيرة في المختبر قبل الإطلاق الحي.${hit?.id === 'compliance' ? '\n• تأكد من اكتمال الامتثال قبل الإطلاق.' : ''}`;
  }
  if (hit) return `${hit.build(ctx, q)}\n\n(رد توضيحي في وضع العرض)`;
  return `نسخة محسّنة (نموذج توضيحي): ${topic}\n\nتُحضَّر على الطريقة الكويتية الأصيلة بمكونات منتقاة وطعم متوازن يحمل ذكرى البيت العائلي، وتُقدَّم طازجة بجودة ثابتة في كل دفعة. مناسبة للمناسبات والضيافة اليومية.\n\nيمكنك أيضاً أن تسألني عن: التسعير، حماية الوصفة، العقود، المستحقات، الامتثال، الإطلاق، التغليف.`;
}
